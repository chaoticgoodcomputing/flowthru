using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Flowthru.Extensions.Python.SourceGenerators;

/// <summary>
/// Generates AddPythonNode overloads for PipelineBuilder supporting up to 8 inputs and 8 outputs.
/// </summary>
/// <remarks>
/// <para>
/// <strong>Phase 5 implementation:</strong>
/// Mirrors PipelineBuilderGenerator's combinatorial approach but for Python nodes.
/// Each overload accepts executor and runtime parameters and delegates to PythonNodeWrapper.
/// </para>
/// <para>
/// Sync-only in Phase 5 — async support deferred to Phase 6.
/// </para>
/// </remarks>
[Generator]
public class PythonNodeGenerator : IIncrementalGenerator
{
  private const int MaxInputs = 8;
  private const int MaxOutputs = 8;

  public void Initialize(IncrementalGeneratorInitializationContext context)
  {
    // Run for any project that references Flowthru.Extensions.Python
    // (unlike PipelineBuilderGenerator which only runs for the core Flowthru assembly)
    context.RegisterPostInitializationOutput(ctx => GenerateAddPythonNode(ctx));
  }

  private static void GenerateAddPythonNode(IncrementalGeneratorPostInitializationContext context)
  {
    var sb = new StringBuilder();

    // File header
    sb.AppendLine(
      """
      // <auto-generated/>
      #nullable enable

      using Flowthru.Data;
      using Flowthru.Extensions.Python.Execution;
      using Flowthru.Extensions.Python.Nodes;
      using Flowthru.Extensions.Python.Runtime;
      using Flowthru.Pipelines;

      namespace Flowthru.Extensions.Python.Nodes;

      public static partial class PythonNodeFactory
      {
      """
    );

    // Generate overloads for all combinations except 1x1 (hand-written)
    for (int inputs = 1; inputs <= MaxInputs; inputs++)
    {
      for (int outputs = 1; outputs <= MaxOutputs; outputs++)
      {
        // Skip 1x1 - it's hand-written for clarity
        if (inputs == 1 && outputs == 1)
        {
          continue;
        }

        // Generate sync version only (Phase 5)
        GenerateAddPythonNode(sb, inputs, outputs);
        sb.AppendLine();
      }
    }

    sb.AppendLine("}");

    context.AddSource(
      "PythonNodeFactory.Generated.cs",
      SourceText.From(sb.ToString(), Encoding.UTF8)
    );
  }

  private static void GenerateAddPythonNode(StringBuilder sb, int inputCount, int outputCount)
  {
    // Generate XML documentation
    GenerateXmlDoc(sb, inputCount, outputCount);

    // Generate type parameters and method signature
    var typeParams = GenerateTypeParameters(inputCount, outputCount);
    var inputParam = GenerateInputParameter(inputCount);
    var outputParam = GenerateOutputParameter(outputCount);

    // Input/Output tuple types for wrapper instantiation
    var inputTupleType = GenerateInputTupleType(inputCount);
    var outputTupleType = GenerateOutputTupleType(outputCount);

    sb.AppendLine(
      $$"""
        public static PipelineBuilder AddPythonNode<{{typeParams}}>(
          this PipelineBuilder builder,
          string label,
          string module,
          string function,
          {{inputParam}} input,
          {{outputParam}} output,
          IPythonExecutor executor,
          string description = ""
        )
        {
      """
    );

    // Generate input deconstruction if needed
    GenerateInputDeconstruction(sb, inputCount);

    // Generate output deconstruction if needed
    GenerateOutputDeconstruction(sb, outputCount);

    // Generate inputs and outputs lists for AddNode
    var inputsList = GenerateInputsList(inputCount);
    var outputsList = GenerateOutputsList(outputCount);

    // Parameter validation
    sb.AppendLine(
      """
          if (builder == null)
          {
            throw new System.ArgumentNullException(nameof(builder));
          }

          if (string.IsNullOrWhiteSpace(label))
          {
            throw new System.ArgumentException("Label cannot be null or whitespace.", nameof(label));
          }

          if (string.IsNullOrWhiteSpace(module))
          {
            throw new System.ArgumentException("Module name cannot be null or whitespace.", nameof(module));
          }

          if (string.IsNullOrWhiteSpace(function))
          {
            throw new System.ArgumentException("Function name cannot be null or whitespace.", nameof(function));
          }

          if (executor == null)
          {
            throw new System.ArgumentNullException(nameof(executor));
          }

      """
    );

    // Create wrapper with tuple types
    sb.AppendLine(
      $$"""
          var wrapper = new PythonNodeWrapper<{{inputTupleType}}, {{outputTupleType}}>(executor, module, function);
          executor.ValidateNode(module, function);

          // Delegate to existing AddNode infrastructure
          return builder.AddNode(
            label: label,
            transform: wrapper.GetTransform(),
            input: input,
            output: output,
            description: description
          );
        }
      """
    );
  }

  private static void GenerateXmlDoc(StringBuilder sb, int inputCount, int outputCount)
  {
    sb.AppendLine(
      $"""
        /// <summary>
        /// Adds a Python node with {inputCount} input{(
        inputCount == 1 ? "" : "s"
      )} and {outputCount} output{(outputCount == 1 ? "" : "s")}.
        /// </summary>
      """
    );

    // Type parameter documentation
    for (int i = 1; i <= inputCount; i++)
    {
      sb.AppendLine($"  /// <typeparam name=\"TIn{i}\">Input type {i}</typeparam>");
    }
    for (int i = 1; i <= outputCount; i++)
    {
      sb.AppendLine($"  /// <typeparam name=\"TOut{i}\">Output type {i}</typeparam>");
    }

    // Parameter documentation
    sb.AppendLine(
      """
        /// <param name="builder">Pipeline builder instance</param>
        /// <param name="label">Unique identifier for this node</param>
        /// <param name="module">Dotted Python module name (e.g., "Pipelines.DataScience.train_model")</param>
        /// <param name="function">Python function name within the module</param>
        /// <param name="input">Catalog entry or tuple of catalog entries providing input data</param>
        /// <param name="output">Catalog entry or tuple of catalog entries to store output data</param>
        /// <param name="executor">Python executor for invoking the function</param>
        /// <param name="description">Optional node description</param>
        /// <returns>This builder for method chaining</returns>
      """
    );
  }

  private static string GenerateTypeParameters(int inputCount, int outputCount)
  {
    var parts = new List<string>();

    for (int i = 1; i <= inputCount; i++)
    {
      parts.Add($"TIn{i}");
    }
    for (int i = 1; i <= outputCount; i++)
    {
      parts.Add($"TOut{i}");
    }

    return string.Join(", ", parts);
  }

  private static string GenerateInputParameter(int inputCount)
  {
    if (inputCount == 1)
    {
      return "ICatalogEntry<TIn1>";
    }

    var types = string.Join(
      ", ",
      Enumerable.Range(1, inputCount).Select(i => $"ICatalogEntry<TIn{i}>")
    );
    return $"({types})";
  }

  private static string GenerateOutputParameter(int outputCount)
  {
    if (outputCount == 1)
    {
      return "ICatalogEntry<TOut1>";
    }

    var types = string.Join(
      ", ",
      Enumerable.Range(1, outputCount).Select(i => $"ICatalogEntry<TOut{i}>")
    );
    return $"({types})";
  }

  private static string GenerateInputTupleType(int inputCount)
  {
    if (inputCount == 1)
    {
      return "TIn1";
    }

    var types = string.Join(", ", Enumerable.Range(1, inputCount).Select(i => $"TIn{i}"));
    return $"({types})";
  }

  private static string GenerateOutputTupleType(int outputCount)
  {
    if (outputCount == 1)
    {
      return "TOut1";
    }

    var types = string.Join(", ", Enumerable.Range(1, outputCount).Select(i => $"TOut{i}"));
    return $"({types})";
  }

  private static void GenerateInputDeconstruction(StringBuilder sb, int inputCount)
  {
    if (inputCount <= 1)
    {
      return;
    }

    sb.Append("    var (");
    for (int i = 1; i <= inputCount; i++)
    {
      if (i > 1)
      {
        sb.Append(", ");
      }
      sb.Append($"input{i}");
    }
    sb.AppendLine(") = input;");
    sb.AppendLine();
  }

  private static void GenerateOutputDeconstruction(StringBuilder sb, int outputCount)
  {
    if (outputCount <= 1)
    {
      return;
    }

    sb.Append("    var (");
    for (int i = 1; i <= outputCount; i++)
    {
      if (i > 1)
      {
        sb.Append(", ");
      }
      sb.Append($"output{i}");
    }
    sb.AppendLine(") = output;");
    sb.AppendLine();
  }

  private static string GenerateInputsList(int inputCount)
  {
    if (inputCount == 1)
    {
      return "input";
    }

    return string.Join(", ", Enumerable.Range(1, inputCount).Select(i => $"input{i}"));
  }

  private static string GenerateOutputsList(int outputCount)
  {
    if (outputCount == 1)
    {
      return "output";
    }

    return string.Join(", ", Enumerable.Range(1, outputCount).Select(i => $"output{i}"));
  }
}
